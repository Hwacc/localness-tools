import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { rolldown, type OutputChunk } from 'rolldown'

const pageDir = resolve(
  dirname(fileURLToPath(import.meta.url)),
  '../src/review/page',
)

async function bundle(input: string) {
  const build = await rolldown({
    input,
    platform: 'browser',
    logLevel: 'silent',
    treeshake: true,
    transform: {
      define: {
        'process.env.NODE_ENV': '"production"',
      },
    },
  })
  try {
    const result = await build.generate({
      format: 'iife',
      codeSplitting: false,
      minify: true,
    })
    const chunks = result.output.filter(
      (item): item is OutputChunk => item.type === 'chunk',
    )
    const chunk = chunks[0]
    if (!chunk || chunks.length !== 1) {
      throw new Error(`Expected one script for ${input}, got ${chunks.length}.`)
    }
    return chunk.code
  } finally {
    await build.close()
  }
}

/** Bundles the review pages and returns the contents of `bundle.gen.ts`. */
export async function buildPages() {
  const style = readFileSync(resolve(pageDir, 'style.css'), 'utf8').replace(
    /\r\n/g,
    '\n',
  )
  const [extract, resolveScript] = await Promise.all([
    bundle(resolve(pageDir, 'client/extract.ts')),
    bundle(resolve(pageDir, 'client/resolve.ts')),
  ])
  return `// Generated by \`pnpm --filter @localness/sdk build:pages\`. Do not edit.
export const EXTRACT_SCRIPT = ${JSON.stringify(extract)}
export const RESOLVE_SCRIPT = ${JSON.stringify(resolveScript)}
export const STYLE = ${JSON.stringify(style)}
`
}

function sameFile(left: string, right: string) {
  return resolve(left).toLowerCase() === resolve(right).toLowerCase()
}

const invoked = process.argv[1]
if (invoked && sameFile(invoked, fileURLToPath(import.meta.url))) {
  writeFileSync(resolve(pageDir, 'bundle.gen.ts'), await buildPages())
}
