function svg(path: string) {
  return readFileSync(path, 'utf8').replace(/\r\n/g, '\n').trim()
}

/** Inlines the flags the page can paint under the webview's closed CSP. */
function flagsModule() {
  const require = createRequire(
    resolve(pageDir, '../../../../vscode/package.json'),
  )
  const flagsRoot = dirname(require.resolve('flag-icons/package.json'))
  const flags: Record<string, string> = {}
  for (const region of FLAG_REGIONS) {
    flags[region] = svg(join(flagsRoot, 'flags/4x3', `${region}.svg`))
  }
  const media = resolve(pageDir, '../../../../vscode/media')
  flags['zh-hans'] = svg(join(media, 'zh-hans.svg'))
  flags['zh-hant'] = svg(join(media, 'zh-hant.svg'))
  return `// Generated by \`pnpm --filter @localness/sdk build:pages\`. Do not edit.
export const FLAGS: Record<string, string> = ${JSON.stringify(flags)}
`
}

function writeIfChanged(path: string, content: string) {
  let current = ''
  try {
    current = readFileSync(path, 'utf8')
  } catch {
    current = ''
  }
  if (current !== content) writeFileSync(path, content)
}

/** Bundles the review pages and returns the contents of `bundle.gen.ts`. */
export async function buildPages() {
  writeIfChanged(resolve(pageDir, 'client/flags.gen.ts'), flagsModule())
  const style = readFileSync(resolve(pageDir, 'style.css'), 'utf8').replace(
    /\r\n/g,
    '\n',
  )
  const [extract, resolveScript, plan] = await Promise.all([
    bundle(resolve(pageDir, 'client/extract.ts')),
    bundle(resolve(pageDir, 'client/resolve.ts')),
    bundle(resolve(pageDir, 'client/plan.ts')),
  ])
  return `// Generated by \`pnpm --filter @localness/sdk build:pages\`. Do not edit.
export const EXTRACT_SCRIPT = ${JSON.stringify(extract)}
export const RESOLVE_SCRIPT = ${JSON.stringify(resolveScript)}
export const PLAN_SCRIPT = ${JSON.stringify(plan)}
export const STYLE = ${JSON.stringify(style)}
`
}

function sameFile(left: string, right: string) {
  return resolve(left).toLowerCase() === resolve(right).toLowerCase()
}

const invoked = process.argv[1]
if (invoked && sameFile(invoked, fileURLToPath(import.meta.url))) {
  writeFileSync(resolve(pageDir, 'bundle.gen.ts'), await buildPages())
}
